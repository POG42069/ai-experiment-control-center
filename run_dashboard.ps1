<#
.SYNOPSIS
    Launch the AI Experiment Control Center Streamlit dashboard locally (127.0.0.1).
.DESCRIPTION
    Does not activate any virtual environment globally; invokes .\.venv\Scripts\python.exe directly.
    Note: ecc/config.py configures demo mode via ecc_config.toml ([general] demo_mode = "on"|"auto"|"off")
    or the ECC_CONFIG path override (it does not use an ECC_DEMO_MODE environment variable).
    When -Demo is passed, this script points ECC_CONFIG at a temporary demo-only TOML file for this session.
#>
[CmdletBinding()]
param(
    [ValidateRange(1024, 65535)]
    [int]$Port = 8501,

    [switch]$Demo
)

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$VenvPython = Join-Path $RepoRoot ".venv\Scripts\python.exe"
$AppEntry = Join-Path $RepoRoot "app\main.py"

if (-not (Test-Path $VenvPython)) {
    Write-Error "Virtual environment not found at '$VenvPython'. Run '.\setup.ps1' first to create .venv and install dependencies."
    exit 1
}

if (-not (Test-Path $AppEntry)) {
    Write-Error "Dashboard entrypoint not found at '$AppEntry'."
    exit 1
}

$prevEccConfig = $env:ECC_CONFIG
$tempDemoConfig = $null

try {
    if ($Demo) {
        $tempDemoConfig = Join-Path ([System.IO.Path]::GetTempPath()) ("ecc_demo_{0}.toml" -f ([System.Guid]::NewGuid().ToString("N")))
        $demoToml = @'
# Temporary demo-only configuration generated by run_dashboard.ps1 -Demo
[general]
demo_mode = "on"
refresh_seconds = 15

[wandb]
entity = ""
projects = []
'@
        # Write UTF-8 without BOM so Python tomllib parses cleanly on Windows PowerShell 5.1
        [System.IO.File]::WriteAllText($tempDemoConfig, $demoToml, (New-Object System.Text.UTF8Encoding($false)))

        $env:ECC_CONFIG = $tempDemoConfig
        Write-Host "[ECC] Demo mode enabled via temporary ECC_CONFIG ($tempDemoConfig)."
        Write-Host "[ECC] Tip: To enable demo mode persistently, set 'demo_mode = `"on`"' under [general] in ecc_config.toml."
    }

    Write-Host "[ECC] Starting dashboard at http://127.0.0.1:$Port ..."
    Push-Location $RepoRoot
    try {
        & $VenvPython -m streamlit run app/main.py --server.address 127.0.0.1 --server.port $Port
        $exitCode = $LASTEXITCODE
    }
    finally {
        Pop-Location
    }
    exit $exitCode
}
finally {
    if ($null -ne $prevEccConfig) {
        $env:ECC_CONFIG = $prevEccConfig
    }
    else {
        Remove-Item Env:ECC_CONFIG -ErrorAction SilentlyContinue
    }
    if ($null -ne $tempDemoConfig -and (Test-Path $tempDemoConfig)) {
        Remove-Item -Path $tempDemoConfig -Force -ErrorAction SilentlyContinue
    }
}
